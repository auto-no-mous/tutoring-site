#!/bin/sh
set -e

# Контейнеры backend и bot собраны из одного образа и стартуют одновременно, то есть
# оба доходят до этой строки. Два параллельных "alembic upgrade head" по одной и той
# же базе - гонка: один накатывает миграции и сдвигает alembic_version, второй в этот
# момент всё ещё держит прежнюю ревизию и падает с
#   FAILED: Online migration expected to match one row when updating
#   '<old>' to '<new>' in 'alembic_version'; 0 found
# После этого он перезапускается по restart-политике и доходит до head, так что до
# сих пор это кончалось лишь пугающей строкой в логе. Но полагаться на перезапуск
# как на механизм миграций нельзя: проигравший мог упасть уже после того, как
# выполнил DDL очередной ревизии, и повторить его на полпути.
#
# Блокировка лежит на общем томе (storage смонтирован в оба контейнера), поэтому
# второй дожидается первого и выполняет затем безобидный no-op - база к тому моменту
# уже на head. Контейнер остаётся самодостаточным: его по-прежнему можно запустить и
# без compose, миграции всё равно применятся.
#
# -w: ждать освобождения, но не вечно. Если за это время первый не закончил, лучше
# упасть с внятной ошибкой (и перезапуститься), чем висеть молча.
flock -w 300 /app/storage/.alembic.lock alembic upgrade head

exec "$@"
