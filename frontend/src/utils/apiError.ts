import axios from "axios";

/**
 * Человекочитаемая причина отказа от API.
 *
 * Бэкенд почти всегда кладёт в `detail` готовый русский текст ("Пользователь с такой
 * почтой уже существует", "Аккаунт временно заблокирован..."), но формы раньше его
 * выбрасывали и показывали одну общую фразу на все случаи. Из-за этого настоящая
 * причина отказа не доходила ни до пользователя, ни до разбора проблемы.
 *
 * Два ответа сюда не укладываются и разобраны отдельно:
 * - 422 от FastAPI: `detail` - это массив описаний полей, а не текст для человека;
 * - 429 от slowapi: ключ `error`, а не `detail`, и текст английский.
 */
export function apiErrorMessage(err: unknown, fallback: string): string {
  if (!axios.isAxiosError(err)) return fallback;

  // Запрос вообще не дошёл до сервера - типичнее всего это оборванная сеть, и
  // предлагать "проверьте данные" здесь бессмысленно.
  if (!err.response) return "Не удалось связаться с сервером. Проверьте соединение и попробуйте ещё раз.";

  if (err.response.status === 429) {
    return "Слишком много попыток. Подождите немного и попробуйте ещё раз.";
  }

  const detail = (err.response.data as { detail?: unknown } | undefined)?.detail;
  if (typeof detail === "string" && detail.trim()) return detail;

  if (err.response.status === 422) return "Проверьте правильность заполнения полей.";
  if (err.response.status >= 500) return "Сервер временно недоступен. Попробуйте ещё раз чуть позже.";

  return fallback;
}
